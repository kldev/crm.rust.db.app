CREATE TABLE crm.users
(
    id                 int GENERATED BY DEFAULT AS IDENTITY,
    login              text           NOT NULL,
    display_name       text           NOT NULL,
    role               text           NOT NULL,
    password_hash      text           NOT NULL,
    is_active          boolean        NOT NULL DEFAULT true,
    failed_login_count int            NOT NULL DEFAULT 0,
    locked_until       timestamptz(3) NULL,
    last_login_at      timestamptz(3) NULL,
    created_at         timestamptz(3) NOT NULL DEFAULT now(),
    created_by         int            NULL,
    updated_at         timestamptz(3) NOT NULL DEFAULT now(),
    updated_by         int            NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_login UNIQUE (login),
    CONSTRAINT ck_users_login CHECK (login ~ '^[a-z0-9._-]{3,64}$'),
    CONSTRAINT ck_users_display_name CHECK (length(display_name) BETWEEN 1 AND 200),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'MANAGER', 'SALES')),
    CONSTRAINT ck_users_failed_login_count CHECK (failed_login_count >= 0)
);

CREATE INDEX ix_users_role ON crm.users (role, id) INCLUDE (is_active);
