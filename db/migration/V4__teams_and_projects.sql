-- Teams deliver projects for clients; one CRM user owns (delivers) each project. Projects move through stages
-- and collect comments (ADR-0005).

CREATE TABLE crm.teams
(
    id           int GENERATED BY DEFAULT AS IDENTITY,
    name         text           NOT NULL,
    lead_user_id int            NOT NULL,
    created_at   timestamptz(3) NOT NULL DEFAULT now(),
    created_by   int            NULL,
    CONSTRAINT pk_teams PRIMARY KEY (id),
    CONSTRAINT ck_teams_name CHECK (length(name) BETWEEN 1 AND 200),
    CONSTRAINT fk_teams_lead_user FOREIGN KEY (lead_user_id) REFERENCES crm.users (id)
);

-- Team names are unique regardless of case (as with the SQL Server collation); a duplicate is 23505 -> 409.
CREATE UNIQUE INDEX uq_teams_name ON crm.teams (lower(name));

CREATE TABLE crm.team_members
(
    team_id   int            NOT NULL,
    user_id   int            NOT NULL,
    joined_at timestamptz(3) NOT NULL DEFAULT now(),
    CONSTRAINT pk_team_members PRIMARY KEY (team_id, user_id),
    CONSTRAINT fk_team_members_team FOREIGN KEY (team_id) REFERENCES crm.teams (id),
    CONSTRAINT fk_team_members_user FOREIGN KEY (user_id) REFERENCES crm.users (id)
);

-- "Which teams am I in" - part of the visibility rule of SALES users.
CREATE UNIQUE INDEX ux_team_members_user ON crm.team_members (user_id, team_id);

-- Allowed stage changes. The rule lives in data: a new transition is an INSERT, not a code release.
CREATE TABLE crm.project_stage_transitions
(
    from_stage text NOT NULL,
    to_stage   text NOT NULL,
    CONSTRAINT pk_project_stage_transitions PRIMARY KEY (from_stage, to_stage)
);

INSERT INTO crm.project_stage_transitions (from_stage, to_stage)
VALUES ('NEW', 'ACCEPTED'),
       ('NEW', 'DECLINED'),
       ('ACCEPTED', 'ACTIVE'),
       ('ACCEPTED', 'DECLINED'),
       ('ACTIVE', 'ON_HOLD'),
       ('ACTIVE', 'CLOSED'),
       ('ON_HOLD', 'ACTIVE'),
       ('ON_HOLD', 'CLOSED');

CREATE TABLE crm.projects
(
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    client_id        bigint         NOT NULL,
    team_id          int            NOT NULL,
    owner_user_id    int            NOT NULL,
    name             text           NOT NULL,
    stage            text           NOT NULL,
    start_date       date           NOT NULL,
    due_date         date           NOT NULL,
    budget           numeric(19, 2) NOT NULL,
    stage_changed_at timestamptz(3) NOT NULL DEFAULT now(),
    created_at       timestamptz(3) NOT NULL DEFAULT now(),
    created_by       int            NULL,
    updated_at       timestamptz(3) NOT NULL DEFAULT now(),
    updated_by       int            NULL,
    CONSTRAINT pk_projects PRIMARY KEY (id),
    CONSTRAINT ck_projects_name CHECK (length(name) BETWEEN 1 AND 200),
    CONSTRAINT ck_projects_stage CHECK (stage IN ('NEW', 'ACCEPTED', 'ACTIVE', 'ON_HOLD', 'CLOSED', 'DECLINED')),
    CONSTRAINT ck_projects_dates CHECK (due_date >= start_date),
    CONSTRAINT ck_projects_budget CHECK (budget >= 0),
    CONSTRAINT fk_projects_client FOREIGN KEY (client_id) REFERENCES crm.clients (id),
    CONSTRAINT fk_projects_team FOREIGN KEY (team_id) REFERENCES crm.teams (id),
    CONSTRAINT fk_projects_owner_user FOREIGN KEY (owner_user_id) REFERENCES crm.users (id)
);

-- Every list of projects is ordered by (due_date, id) and paged by keyset; each index ends with those columns.
CREATE INDEX ix_projects_client ON crm.projects (client_id, due_date, id) INCLUDE (stage, team_id, owner_user_id);
CREATE INDEX ix_projects_team ON crm.projects (team_id, due_date, id) INCLUDE (stage, client_id, owner_user_id);
CREATE INDEX ix_projects_owner ON crm.projects (owner_user_id, due_date, id) INCLUDE (stage, client_id, team_id);
CREATE INDEX ix_projects_stage ON crm.projects (stage, due_date, id) INCLUDE (team_id, client_id, owner_user_id);
-- All projects by due date (MANAGER/ADMIN without filters).
CREATE INDEX ix_projects_due ON crm.projects (due_date, id) INCLUDE (stage, team_id, client_id, owner_user_id);
-- Overdue = open project after its due date: a partial index on open projects only.
CREATE INDEX ix_projects_open_due ON crm.projects (due_date, id) INCLUDE (stage, team_id, client_id, owner_user_id)
    WHERE stage IN ('NEW', 'ACCEPTED', 'ACTIVE', 'ON_HOLD');

CREATE TABLE crm.project_stage_history
(
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    project_id bigint         NOT NULL,
    from_stage text           NULL,
    to_stage   text           NOT NULL,
    changed_at timestamptz(3) NOT NULL DEFAULT now(),
    changed_by int            NULL,
    CONSTRAINT pk_project_stage_history PRIMARY KEY (id),
    CONSTRAINT fk_project_stage_history_project FOREIGN KEY (project_id) REFERENCES crm.projects (id)
);

-- History is always read per project, newest first.
CREATE UNIQUE INDEX ux_project_stage_history_project ON crm.project_stage_history (project_id, id);

CREATE TABLE crm.project_comments
(
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    project_id bigint         NOT NULL,
    author_id  int            NOT NULL,
    body       text           NOT NULL,
    created_at timestamptz(3) NOT NULL DEFAULT now(),
    CONSTRAINT pk_project_comments PRIMARY KEY (id),
    CONSTRAINT ck_project_comments_body CHECK (length(body) BETWEEN 1 AND 4000),
    CONSTRAINT fk_project_comments_project FOREIGN KEY (project_id) REFERENCES crm.projects (id),
    CONSTRAINT fk_project_comments_author FOREIGN KEY (author_id) REFERENCES crm.users (id)
);

-- Comments of one project, newest first, paged by id: one range of the index.
CREATE UNIQUE INDEX ux_project_comments_project ON crm.project_comments (project_id, id);

/*
  Number of projects and budget per team and stage (ADR-0015). PostgreSQL has no indexed views: the procedures
  that write crm.projects keep this table in step in the same transaction (crm.team_stats_move), so the team
  statistics read at most 6 rows however many projects a team has.
*/
CREATE TABLE crm.team_project_stats
(
    team_id       int            NOT NULL,
    stage         text           NOT NULL,
    project_count bigint         NOT NULL DEFAULT 0,
    budget_total  numeric(19, 2) NOT NULL DEFAULT 0,
    CONSTRAINT pk_team_project_stats PRIMARY KEY (team_id, stage),
    CONSTRAINT fk_team_project_stats_team FOREIGN KEY (team_id) REFERENCES crm.teams (id),
    CONSTRAINT ck_team_project_stats_count CHECK (project_count >= 0)
);
