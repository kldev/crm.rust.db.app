CREATE TABLE crm.clients
(
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    name             text           NOT NULL,
    nip              text           NULL,
    email            text           NULL,
    phone            text           NULL,
    city             text           NULL,
    status           text           NOT NULL,
    assigned_user_id int            NULL,
    note             text           NULL,
    created_at       timestamptz(3) NOT NULL DEFAULT now(),
    created_by       int            NULL,
    updated_at       timestamptz(3) NOT NULL DEFAULT now(),
    updated_by       int            NULL,
    CONSTRAINT pk_clients PRIMARY KEY (id),
    CONSTRAINT ck_clients_name CHECK (length(name) BETWEEN 1 AND 200),
    CONSTRAINT ck_clients_nip CHECK (nip ~ '^[0-9]{10}$'),
    CONSTRAINT ck_clients_email CHECK (length(email) <= 254),
    CONSTRAINT ck_clients_phone CHECK (length(phone) <= 30),
    CONSTRAINT ck_clients_city CHECK (length(city) <= 100),
    CONSTRAINT ck_clients_note CHECK (length(note) <= 2000),
    CONSTRAINT ck_clients_status CHECK (status IN ('LEAD', 'ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_clients_assigned_user FOREIGN KEY (assigned_user_id) REFERENCES crm.users (id)
);

-- Exact lookups. A duplicate NIP fails on ux_clients_nip (23505 -> 409).
CREATE UNIQUE INDEX ux_clients_nip ON crm.clients (nip) WHERE nip IS NOT NULL;
CREATE INDEX ix_clients_email ON crm.clients (email) WHERE email IS NOT NULL;

-- Name search is a case-insensitive prefix (as the SQL Server collation was): the key is lower(name) in the "C"
-- collation, so `LIKE 'abc%'` is a range on the index and the order is the same index (byte order of the
-- lower-case name, then id). Keyset pages by name read (lower(name), id).
CREATE INDEX ix_clients_name ON crm.clients ((lower(name) COLLATE "C"), id);
-- SALES sees only own clients: newest first by owner, and name prefix by owner.
CREATE INDEX ix_clients_assigned_user ON crm.clients (assigned_user_id, id);
CREATE INDEX ix_clients_assigned_user_name ON crm.clients (assigned_user_id, (lower(name) COLLATE "C"), id);
CREATE INDEX ix_clients_city ON crm.clients (city, id);
