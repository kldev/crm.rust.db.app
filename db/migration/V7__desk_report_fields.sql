/*
  Report data of desk tickets (ADR-0010): a subcategory collects its own fields - a Limosa number, the dates of a
  posting, a new employee's PESEL, an invoice amount - validated by the procedures, stored in the ticket's events and
  read by the reports. A field key is stored on tickets: it is never renamed or reused, and one key means one thing in
  every subcategory (only "required" may differ, per subcategory). Copied from Halcyon's catalog (Polish labels).
*/
CREATE TABLE crm.desk_fields
(
    field_key   text NOT NULL,
    label       text NOT NULL,
    kind        text NOT NULL,
    placeholder text NULL,
    CONSTRAINT pk_desk_fields PRIMARY KEY (field_key),
    CONSTRAINT ck_desk_fields_kind CHECK (kind IN ('TEXT', 'DATE', 'EMAIL', 'CHOICE', 'AMOUNT', 'IBAN', 'COUNT',
                                                   'MULTI_CHOICE', 'TICKET_NUMBER'))
);

-- The values of CHOICE and MULTI_CHOICE fields, in the order the form lists them; favourites are offered first.
CREATE TABLE crm.desk_field_options
(
    field_key    text    NOT NULL,
    option_value text    NOT NULL,
    sort_order   int     NOT NULL,
    is_favorite  boolean NOT NULL,
    CONSTRAINT pk_desk_field_options PRIMARY KEY (field_key, option_value),
    CONSTRAINT fk_desk_field_options_field FOREIGN KEY (field_key) REFERENCES crm.desk_fields (field_key)
);

CREATE TABLE crm.desk_subcategory_fields
(
    subcategory_key text    NOT NULL,
    field_key       text    NOT NULL,
    sort_order      int     NOT NULL,
    is_required     boolean NOT NULL,
    CONSTRAINT pk_desk_subcategory_fields PRIMARY KEY (subcategory_key, field_key),
    CONSTRAINT fk_desk_subcategory_fields_sub FOREIGN KEY (subcategory_key)
        REFERENCES crm.desk_subcategories (subcategory_key),
    CONSTRAINT fk_desk_subcategory_fields_field FOREIGN KEY (field_key) REFERENCES crm.desk_fields (field_key)
);

-- The read model of a ticket's report data: the current value of each field that has one.
CREATE TABLE crm.ticket_fields
(
    ticket_id bigint NOT NULL,
    field_key text   NOT NULL,
    value     text   NOT NULL,
    CONSTRAINT pk_ticket_fields PRIMARY KEY (ticket_id, field_key),
    CONSTRAINT fk_ticket_fields_ticket FOREIGN KEY (ticket_id) REFERENCES crm.tickets (id),
    CONSTRAINT fk_ticket_fields_field FOREIGN KEY (field_key) REFERENCES crm.desk_fields (field_key),
    CONSTRAINT ck_ticket_fields_value CHECK (length(value) BETWEEN 1 AND 200)
);

-- Campaigns ordered for a recruitment ticket: marketing tickets whose related-ticket is that ticket's number.
CREATE INDEX ix_ticket_fields_value ON crm.ticket_fields (field_key, value);

